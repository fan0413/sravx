    await page.getByRole('button', { name: '播放自动展示', exact: true }).click()
    await page.mouse.move(0, 0)
    await page.locator('.showcase-play').evaluate(el => el.blur())
    await title(page, 2)
    await page.locator('.showcase-viewport').hover()
    await page.waitForTimeout(600)
    const hoverTitle = await page.locator('.showcase-info h1').innerText()
    await page.waitForTimeout(5000)
    assert.equal(await page.locator('.showcase-info h1').innerText(), hoverTitle)
    await page.getByRole('button', { name: '进入官网', exact: false }).click()
    await page.waitForURL(/#\/pages\/index\/index/)
    await page.locator('.stage-product-pro').waitFor()
    await page.reload({ waitUntil: 'domcontentloaded' })
    await page.locator('.stage-product-pro').waitFor()
    assert.equal(await page.locator('.scissor-showcase').count(), 0)
    const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
    mobile.on('pageerror', error => errors.push(error.message))
    await mobile.emulateMedia({ reducedMotion: 'reduce' })
    await mobile.goto(base + '#/pages/welcome/index', { waitUntil: 'domcontentloaded' })
