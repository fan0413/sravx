    await title(mobile, 0)
    await fits(mobile)
    assert.equal(await mobile.locator('.showcase-copy h1').evaluate(el => getComputedStyle(el).animationName), 'none')
    assert.equal(await mobile.getByRole('button', { name: '播放自动展示', exact: true }).count(), 1)
    await mobile.waitForTimeout(4800)
    await title(mobile, 0)
    const cdp = await mobile.context().newCDPSession(mobile)
    const box = await mobile.locator('.showcase-viewport').boundingBox()
    const x = box.x + box.width / 2, y = box.y + box.height / 2
    async function touch(dx, dy) {
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: x + 60, y }] })
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x + 60 + dx, y: y + dy }] })
      await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    }
    await touch(-130, 0)
    await title(mobile, 1)
    await touch(0, -90)
    await title(mobile, 1)
    await mobile.evaluate(() => window.scrollTo(0, 0))
    await mobile.screenshot({ path: output + '/mobile.png', fullPage: true })
    await mobile.setViewportSize({ width: 320, height: 568 })
    for (let index = 0; index < 4; index++) {
      await mobile.locator('.showcase-dot').nth(index).click()
      await title(mobile, index)
      await fits(mobile)
    }
    await mobile.evaluate(() => window.scrollTo(0, 0))
    await mobile.screenshot({ path: output + '/small-mobile.png', fullPage: true })
    await mobile.getByRole('button', { name: '进入官网', exact: false }).click()
    await mobile.locator('.stage-product-pro').waitFor()
    // Restored navigation uses existing destinations, without logging in.
    await page.goto(base + '#/pages/welcome/index', { waitUntil: 'domcontentloaded' })
    await ready(page)
    await page.locator('.nav-trigger').filter({ hasText: '产品' }).hover()
    await page.locator('.mega-link').filter({ hasText: 'Basic 系列' }).click()
    await page.waitForURL(/#\/pages\/shop\/index\?series=basic/)
